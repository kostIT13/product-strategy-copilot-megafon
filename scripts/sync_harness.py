"""Generate/check thin IDE adapters from the repository canon, never edit host-global config."""
import argparse
import hashlib
import json
from pathlib import Path
import re

MARKER = "Generated by scripts/sync_harness.py"


def safe_path(root, name):
    path = root / name
    if not path.resolve().is_relative_to(root) or any(p.is_symlink() for p in (path, *path.parents) if p.is_relative_to(root)):
        raise ValueError("harness paths must stay inside the root without symlinks")
    return path


def expected_files(root):
    manifest = json.loads(safe_path(root, "agent/harness.json").read_text(encoding="utf-8"))
    navigation = manifest.get("navigation", [])
    if (not isinstance(navigation, list) or len(navigation) > 2
            or any(not isinstance(name, str) or name not in {"agent/README.md", "agent/automation.md"} for name in navigation)
            or len(set(navigation)) != len(navigation)):
        raise ValueError("invalid canonical navigation")
    skills = sorted({name for profile in manifest["stages"].values() for name in profile["skills"]})
    if any(not re.fullmatch(r"[a-z0-9-]{1,64}", name) for name in skills):
        raise ValueError("invalid canonical skill name")
    files = ["AGENTS.md", "agent/harness.json", "agent/workflow.md", "agent/quality.md", "agent/safety.md", "knowledge/catalog.json", "agent/hosts/catalog.json"]
    files += navigation
    files += [f".agents/skills/{name}/SKILL.md" for name in skills]
    role_catalog = json.loads(safe_path(root, "agent/roles/catalog.json").read_text(encoding="utf-8"))
    if (set(role_catalog) != {"schema_version", "roles"} or type(role_catalog["schema_version"]) is not int
            or role_catalog["schema_version"] != 1 or not isinstance(role_catalog["roles"], dict)
            or set(role_catalog["roles"]) != {"research", "evidence", "critic"}
            or any(not isinstance(version, str) or len(version) > 40 or re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version) is None for version in role_catalog["roles"].values())):
        raise ValueError("invalid canonical role catalog")
    files += ["agent/roles/catalog.json", *[f"agent/roles/{role}.md" for role in sorted(role_catalog["roles"])]]
    catalog = json.loads(safe_path(root, "knowledge/catalog.json").read_text(encoding="utf-8"))
    for item in catalog["documents"]:
        if not item["path"].startswith("knowledge/") or not item["path"].endswith(".md"):
            raise ValueError("invalid knowledge path")
        files.append(item["path"])
    canonical = {name: safe_path(root, name).read_text(encoding="utf-8") for name in sorted(set(files))}
    digest = hashlib.sha256(json.dumps(canonical, ensure_ascii=False, sort_keys=True).encode()).hexdigest()
    marker = f"<!-- {MARKER}; canon sha256: {digest}. Do not edit. -->\n"
    outputs = {
        "CLAUDE.md": marker + "# Product Strategy Agent\n\n@AGENTS.md\n\nRead agent/README.md for stage-scoped skills and knowledge. No automatic publication or model calls.\n",
        "QWEN.md": marker + "# Product Strategy Agent\n\nRead [AGENTS.md](AGENTS.md) in full, then [agent/README.md](agent/README.md). For a case, run `psa context ID` and read its selected materials. Do not infer consent or native skill loading from this file.\n",
        ".cursor/rules/product-strategy.mdc": '---\ndescription: Product strategy project instructions and workflow\nalwaysApply: true\n---\n\n' + marker + "Read [AGENTS.md](../../AGENTS.md) before working. For product cases read agent/README.md and run psa context ID; use only the selected procedures and retain human gates.\n",
        ".codex/README.md": marker + "# Codex adapter\n\nCanonical instructions: [AGENTS.md](../AGENTS.md); skills: [.agents/skills](../.agents/skills/psa-research/SKILL.md). For explicit subagent/hook/diagnostics tasks read [automation](../agent/automation.md). This README is not executable configuration and enables no dispatch, hooks or MCP connection. The optional server uses FastMCP stdio; native acceptance/activation remains separate. Start a fresh session, inspect loaded instructions/skills, and follow the [acceptance runbook](../docs/ide-instructions.md). Host loading is not yet verified.\n",
        ".claude/README.md": marker + "# Claude adapter\n\n[CLAUDE.md](../CLAUDE.md) imports the canon. skills/ contains generated copies of .agents/skills with no independent business rules. For opt-in subagents, local hooks and diagnostics use [automation](../agent/automation.md); these files do not activate native execution. See the [acceptance runbook](../docs/ide-instructions.md); host loading is not yet verified.\n",
    }
    for name in skills:
        content = canonical[f".agents/skills/{name}/SKILL.md"]
        end = content.index("\n---", 3) + 4
        outputs[f".claude/skills/{name}/SKILL.md"] = content[:end] + "\n\n" + marker + content[end:].lstrip("\n")
    return outputs


def sync(root, write=False):
    root = root.resolve()
    outputs = expected_files(root)
    differences = []
    for name, expected in outputs.items():
        path = safe_path(root, name)
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != expected:
            if write:
                if current is not None and MARKER not in current[:1024]:
                    raise ValueError(f"refusing to overwrite unmanaged adapter: {name}")
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected, encoding="utf-8")
            else:
                differences.append(name)
    # Stale copies must fail check instead of silently continuing as a second canon.
    folder = safe_path(root, ".claude/skills")
    stale = [path.relative_to(root).as_posix() for path in folder.glob("psa-*/SKILL.md")
             if path.relative_to(root).as_posix() not in outputs]
    return {"ok": not differences and not stale, "differences": differences, "stale": sorted(stale),
            "managed_files": len(outputs), "mode": "write" if write else "check"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--check", action="store_true")
    modes.add_argument("--write", action="store_true")
    args = parser.parse_args()
    try:
        result = sync(args.root, args.write)
    except (ValueError, OSError, KeyError, TypeError) as exc:
        result = {"ok": False, "error": str(exc) if type(exc) is ValueError else "invalid harness configuration"}
    print(json.dumps(result, ensure_ascii=True))
    return 0 if result["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
