"""Atomic correction append with captured current evidence and immutable receipts."""

from contextlib import AbstractContextManager
from typing import Protocol


class ClaimCorrectionStore(Protocol):
    def access(self, project_id: str) -> AbstractContextManager: ...
    def replay(self, project_id, command) -> dict | None: ...
    def capture_correction(self, project_id: str) -> dict: ...
    def correction_evidence(self, project_id: str): ...
    def commit_correction(self, project_id, command, snapshot, timestamp) -> dict: ...
