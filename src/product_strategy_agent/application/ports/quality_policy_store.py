"""Coherent policy inspection and atomic enablement boundary."""

from contextlib import AbstractContextManager
from typing import Protocol


class QualityPolicyStore(Protocol):
    def access(self, project_id: str) -> AbstractContextManager: ...
    def replay(self, project_id, command) -> dict | None: ...
    def capture(self, project_id: str) -> dict: ...
    def commit(self, project_id, command, snapshot, timestamp) -> dict: ...
