"""Coherent review packet, immutable audit and gate proof boundary."""

from contextlib import AbstractContextManager
from typing import Protocol


class SemanticReviewStore(Protocol):
    def access(self, project_id: str) -> AbstractContextManager: ...
    def replay(self, project_id, command) -> dict | None: ...
    def capture(self, project_id: str) -> dict: ...
    def checks(self, project_id, scope, snapshot) -> dict: ...
    def commit(self, project_id, command, snapshot, packet, timestamp) -> dict: ...
    def require_gate_review(
        self, project_id, scope, operation_id, packet
    ) -> dict | None: ...
