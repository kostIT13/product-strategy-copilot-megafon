"""Unit-of-work boundary over the shared state/events journal."""
from contextlib import AbstractContextManager
from typing import Protocol
from product_strategy_agent.domain.projects.mode_change import ModeChange


class ModeWorkflowStore(Protocol):
    def access(self, project_id: str) -> AbstractContextManager: ...
    def capture(self, project_id: str) -> dict: ...
    def replay(self, project_id: str, command: ModeChange) -> dict | None: ...
    def commit(self, project_id: str, command: ModeChange, before_state: bytes, after_state: dict,
               before_events: bytes, event: dict, inputs: dict) -> dict: ...
