"""Render unit-of-work over the shared publication journal."""
from contextlib import AbstractContextManager
from typing import Protocol
from product_strategy_agent.domain.projects.render_plan import RenderRequest


class RenderStore(Protocol):
    def access(self, project_id: str) -> AbstractContextManager: ...
    def replay(self, project_id: str, command: RenderRequest) -> dict | None: ...
    def capture_render(self, project_id: str) -> dict: ...
    def commit_render(self, project_id: str, command: RenderRequest, snapshot: dict, timestamp: str) -> dict: ...
