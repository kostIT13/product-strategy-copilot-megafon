"""Capture/read/commit boundaries for one source import without hidden external retry."""
from contextlib import AbstractContextManager
from typing import Protocol
from product_strategy_agent.domain.projects.source_import import SourceImport


class SourceReader(Protocol):
    def read(self, command: SourceImport) -> tuple[dict, bytes]: ...


class SourceImportStore(Protocol):
    def access(self, project_id: str) -> AbstractContextManager: ...
    def replay(self, project_id: str, command: SourceImport) -> dict | None: ...
    def capture(self, project_id: str) -> dict: ...
    def capture_source(self, project_id: str, snapshot: dict, material: dict, text: bytes) -> dict: ...
    def commit_source(self, project_id: str, command: SourceImport, snapshot: dict, material: dict, text: bytes, timestamp: str) -> dict: ...
