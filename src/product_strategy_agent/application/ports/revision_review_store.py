"""Atomic access/capture/commit boundary for revision-review operations."""
from contextlib import AbstractContextManager
from typing import Protocol
from product_strategy_agent.domain.projects.revision_review import RevisionReview


class RevisionReviewStore(Protocol):
    def access(self, project_id: str) -> AbstractContextManager: ...
    def capture_review(self, project_id: str, revision_event_id: str) -> dict: ...
    def replay(self, project_id: str, command: RevisionReview) -> dict | None: ...
    def commit(self, project_id: str, command: RevisionReview, before_state: bytes, after_state: dict,
               before_events: bytes, event: dict, inputs: dict) -> dict: ...
