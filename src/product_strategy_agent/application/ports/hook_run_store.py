"""Explicit run lifecycle; journal writes stay outside canonical case inputs."""

from typing import Protocol
from contextlib import AbstractContextManager
from product_strategy_agent.domain.automation.hook_runs import HookRun, HookCompletion


class HookRunStore(Protocol):
    def access(self, project_id: str) -> AbstractContextManager: ...
    def read(self, project_id, operation_id): ...
    def begin(self, project_id: str, command: HookRun): ...
    def finish(self, project_id: str, command: HookRun, result: HookCompletion): ...
    def pending(self, project_id: str): ...


class HookRunner(Protocol):
    def execute(self, command: HookRun): ...
