"""Host observations are isolated from case state and host configuration."""

from typing import Protocol


class HostAcceptanceStore(Protocol):
    def access(self): ...
    def read(self, operation_id): ...
    def publish(self, record): ...
    def pending(self): ...
    def recover(self, operation_id): ...


class HostEvidenceReader(Protocol):
    def capture(self, selections): ...
