"""A single visible HEAD commits an entire immutable artifact/event/receipt bundle."""
from typing import Protocol
from uuid import UUID
from product_strategy_agent.domain.projects.research_artifact import RecordResearchArtifact


class ResearchArtifactStore(Protocol):
    def status(self, project_id: str) -> dict: ...
    def record(self, project_id: str, command: RecordResearchArtifact) -> dict: ...
    def show(self, project_id: str, operation_id: UUID | None = None) -> dict: ...
    def pending(self, project_id: str) -> list[dict]: ...
    def recover(self, project_id: str, operation_id: UUID) -> dict: ...
